# --- Phase 4: Mediation ---

class CellConflict(BaseModel):
    facet: FACETS
    dimension: CT_DIMENSIONS
    main_summary: str
    challenger_summary: str
    challenger_response_type: Literal["challenge", "reframe", "confirm"]
    implication: str
    conflict_type: CONFLICT_TYPE
    conflict_type_rationale: str
    severity: int = Field(ge=1, le=5)
    resolvability: RESOLVABILITY

    @field_validator("implication")
    @classmethod
    def implication_must_reveal(cls, v: str) -> str:
        v = v.strip()
        starters = ("this reveals", "this suggests", "this exposes",
                    "this shows", "this uncovers", "this indicates")
        if not any(v.lower().startswith(s) for s in starters):
            raise ValueError(
                f"implication must begin with 'This reveals that...' etc. Got: {v[:80]!r}"
            )
        if len(v) < 60:
            raise ValueError(f"implication too short ({len(v)} chars): {v!r}")
        return v

    @field_validator("conflict_type_rationale")
    @classmethod
    def rationale_must_be_substantive(cls, v: str) -> str:
        if len(v.strip()) < 40:
            raise ValueError("conflict_type_rationale must be at least one complete sentence")
        return v.strip()

    @model_validator(mode="after")
    def resolvability_consistent_with_type(self) -> "CellConflict":
        forbidden = get_forbidden_resolvabilities(self.conflict_type)
        if self.resolvability in forbidden:
            raise ValueError(
                f"resolvability='{self.resolvability}' is inconsistent with "
                f"conflict_type='{self.conflict_type}'. "
                f"A {self.conflict_type} conflict cannot be resolved this way."
            )
        return self

 
class WholenessImplyingNodes(BaseModel):
    """Distilled output that feeds the next cycle and constrains final generation."""
    query_assumptions: list[str]
    reformulated_query: str | None
    new_objective: str | None
    updated_challenger_perspective: str | None
    objective_assumptions: list[str]
    perspective_assumptions: list[str]


class ImplyingNodes(BaseModel):
    cycle: int
    agreements: list[str]
    conflicts: list[CellConflict]
    what_conflicts_imply: list[str]
    updated_assumptions: list[str]
    wholeness: WholenessImplyingNodes
    converged: bool
    conflict_type_summary: ConflictTypeSummary | None = None

    @model_validator(mode="after")
    def compute_type_summary(self) -> "ImplyingNodes":
        self.conflict_type_summary = ConflictTypeSummary.from_conflicts(
            self.conflicts, scope="cycle", cycles_included=[self.cycle]
        )
        return self

    def to_cell_context(self, cycle: int) -> dict | None:
        """Structured, labeled guidance for injection into the next cycle's cells.

        Replaces the lossy prose round-trip of _build_prior_findings: the cell
        agent receives named fields it can reason about by name instead of an
        unlabeled paragraph. Includes updated_assumptions (which live on
        ImplyingNodes, not wholeness — the reason this method is here and not on
        WholenessImplyingNodes). Returns None when nothing is actionable.
        """
        w = self.wholeness
        guidance: dict = {}
        if w.reformulated_query:
            guidance["reformulated_query"] = w.reformulated_query
        if w.new_objective:
            guidance["new_objective"] = w.new_objective
        if w.query_assumptions:
            guidance["query_assumptions"] = w.query_assumptions
        if w.objective_assumptions:
            guidance["objective_assumptions"] = w.objective_assumptions
        if self.updated_assumptions:
            guidance["updated_assumptions"] = self.updated_assumptions
        if not guidance:
            return None
        return {
            "from_cycle": cycle,
            "guidance": guidance,
            "_note": (
                "This guidance was produced by the mediator in the previous cycle. "
                "Use it to refine your analysis — do not simply repeat it."
            ),
        }


