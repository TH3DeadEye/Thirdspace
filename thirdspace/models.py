# The five conflict types — one per generative mechanism.
CONFLICT_TYPE = Literal[
    "semantic",       # same words, different operational meaning — about vocabulary, not position
    "attributional",  # shared facts (agree on the sequence), disagree on who caused what
    "normative",      # mutual understanding, incompatible value frameworks
    "structural",     # situation-generated by power distribution — reproduces under any occupants
    "factual",        # disagree about the bare sequence of events
]

RESOLVABILITY = Literal[
    "conversational",     # parties can resolve directly
    "facilitated",        # needs a third-party facilitator
    "structural_change",  # requires redesigning the situation
    "external_standard",  # requires a standard neither party sets
    "unresolvable",       # no available standard or evidence
]

